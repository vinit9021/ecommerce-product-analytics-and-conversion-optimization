"""A/B experimentation utilities for the Product Analytics case study.

The experiment readout generated by this module is synthetic and is used
only to demonstrate Product Analyst experimentation methodology.
"""

from __future__ import annotations

import csv
import math
from dataclasses import dataclass
from pathlib import Path

import numpy as np
from scipy.stats import norm
from statsmodels.stats.power import NormalIndPower
from statsmodels.stats.proportion import (
    proportion_effectsize,
    proportions_ztest,
)


@dataclass(frozen=True)
class ExperimentConfig:
    """Configuration for the planned product experiment."""

    baseline_rate: float = 0.1703
    relative_mde: float = 0.10
    alpha: float = 0.05
    power: float = 0.80


def required_sample_size(config: ExperimentConfig) -> int:
    """Return required observations per experiment variant."""

    target_rate = config.baseline_rate * (1 + config.relative_mde)

    effect_size = proportion_effectsize(
        target_rate,
        config.baseline_rate,
    )

    power_analysis = NormalIndPower()

    sample_size = power_analysis.solve_power(
        effect_size=abs(effect_size),
        alpha=config.alpha,
        power=config.power,
        ratio=1.0,
        alternative="two-sided",
    )

    return math.ceil(sample_size)


def analyze_experiment(
    control_visitors: int,
    control_conversions: int,
    treatment_visitors: int,
    treatment_conversions: int,
    alpha: float = 0.05,
) -> dict[str, float | str]:
    """Analyze a two-arm binary-conversion experiment."""

    control_rate = control_conversions / control_visitors
    treatment_rate = treatment_conversions / treatment_visitors

    absolute_lift = treatment_rate - control_rate

    relative_lift = (
        absolute_lift / control_rate
        if control_rate > 0
        else np.nan
    )

    counts = np.array(
        [
            treatment_conversions,
            control_conversions,
        ]
    )

    observations = np.array(
        [
            treatment_visitors,
            control_visitors,
        ]
    )

    z_statistic, p_value = proportions_ztest(
        count=counts,
        nobs=observations,
        alternative="two-sided",
    )

    standard_error = math.sqrt(
        (
            control_rate
            * (1 - control_rate)
            / control_visitors
        )
        + (
            treatment_rate
            * (1 - treatment_rate)
            / treatment_visitors
        )
    )

    critical_value = norm.ppf(1 - alpha / 2)

    ci_low = absolute_lift - critical_value * standard_error
    ci_high = absolute_lift + critical_value * standard_error

    statistically_significant = (
        p_value < alpha
        and absolute_lift > 0
        and ci_low > 0
    )

    decision = (
        "SIGNIFICANT POSITIVE LIFT"
        if statistically_significant
        else "NO SIGNIFICANT POSITIVE LIFT"
    )

    return {
        "control_rate": control_rate,
        "treatment_rate": treatment_rate,
        "absolute_lift": absolute_lift,
        "relative_lift": relative_lift,
        "z_statistic": float(z_statistic),
        "p_value": float(p_value),
        "ci_low": ci_low,
        "ci_high": ci_high,
        "decision": decision,
    }


def write_outputs(
    config: ExperimentConfig,
    sample_size: int,
    results: dict[str, float | str],
) -> None:
    """Write synthetic experiment outputs."""

    processed_dir = Path("data/processed")
    docs_dir = Path("docs")

    processed_dir.mkdir(parents=True, exist_ok=True)
    docs_dir.mkdir(parents=True, exist_ok=True)

    csv_path = processed_dir / "experiment_results.csv"

    with csv_path.open(
        "w",
        newline="",
        encoding="utf-8",
    ) as file:
        writer = csv.writer(file)

        writer.writerow(["metric", "value"])

        for key, value in results.items():
            writer.writerow([key, value])

    target_rate = config.baseline_rate * (
        1 + config.relative_mde
    )

    markdown = f"""# Synthetic Experiment Readout

## Important

This is a synthetic statistical demonstration.

The GA4 public dataset does not contain a real experiment assignment, so the
results below must not be interpreted as observed product impact.

## Experiment Planning

- Baseline View → Cart rate: {config.baseline_rate:.2%}
- Relative MDE: {config.relative_mde:.1%}
- Target conversion: {target_rate:.2%}
- Significance level: {config.alpha:.0%}
- Statistical power: {config.power:.0%}
- Required sample size per variant: {sample_size:,}
- Total planned sample: {sample_size * 2:,}

## Synthetic Readout

- Control conversion: {results["control_rate"]:.2%}
- Treatment conversion: {results["treatment_rate"]:.2%}
- Absolute lift: {float(results["absolute_lift"]) * 100:.2f} percentage points
- Relative lift: {float(results["relative_lift"]):.2%}
- p-value: {float(results["p_value"]):.4f}
- 95% CI for absolute lift:
  {float(results["ci_low"]) * 100:.2f} to
  {float(results["ci_high"]) * 100:.2f} percentage points
- Statistical readout: {results["decision"]}

## Interpretation

The synthetic example demonstrates how a Product Analyst would determine
whether an observed conversion lift is statistically distinguishable from
random variation.

A real ship decision would additionally require satisfactory guardrail
metrics and business significance.
"""

    (
        docs_dir / "experiment_results.md"
    ).write_text(
        markdown,
        encoding="utf-8",
    )


def main() -> None:
    """Run the reproducible synthetic experiment example."""

    config = ExperimentConfig()

    sample_size = required_sample_size(config)

    # Deterministic synthetic counts approximating:
    # Control: 17.03%
    # Treatment: 18.73%
    #
    # These are NOT observed GA4 experiment results.
    control_visitors = sample_size
    treatment_visitors = sample_size

    control_conversions = round(
        control_visitors * config.baseline_rate
    )

    treatment_conversions = round(
        treatment_visitors
        * config.baseline_rate
        * (1 + config.relative_mde)
    )

    results = analyze_experiment(
        control_visitors=control_visitors,
        control_conversions=control_conversions,
        treatment_visitors=treatment_visitors,
        treatment_conversions=treatment_conversions,
        alpha=config.alpha,
    )

    write_outputs(
        config=config,
        sample_size=sample_size,
        results=results,
    )

    print("Synthetic A/B experiment analysis")
    print("--------------------------------")
    print(f"Sample size per variant: {sample_size:,}")
    print(
        "Control conversion: "
        f"{results['control_rate']:.2%}"
    )
    print(
        "Treatment conversion: "
        f"{results['treatment_rate']:.2%}"
    )
    print(
        "Absolute lift: "
        f"{float(results['absolute_lift']) * 100:.2f} pp"
    )
    print(
        "Relative lift: "
        f"{float(results['relative_lift']):.2%}"
    )
    print(
        f"p-value: {float(results['p_value']):.4f}"
    )
    print(
        "95% CI: "
        f"[{float(results['ci_low']) * 100:.2f}, "
        f"{float(results['ci_high']) * 100:.2f}] pp"
    )
    print(f"Decision: {results['decision']}")
    print()
    print(
        "Reminder: this experiment result is synthetic."
    )


if __name__ == "__main__":
    main()
